    private static readonly Random _random = Random.Shared;

    public (string Quote, SavingsTier Tier) GetQuote(decimal amount)
    {
        var tier = GetTier(amount);
        var pool = tier switch
        {
            SavingsTier.Zero => ZeroQuotes,
            SavingsTier.Low => LowQuotes,
            SavingsTier.Medium => MediumQuotes,
            SavingsTier.High => HighQuotes,
            _ => ZeroQuotes
        };

        return (pool[_random.Next(pool.Length)], tier);
    }

    private static SavingsTier GetTier(decimal amount)
    {
        if (amount <= 0) return SavingsTier.Zero;
        if (amount <= LowMax) return SavingsTier.Low;
        if (amount <= MediumMax) return SavingsTier.Medium;
        return SavingsTier.High;
    }
